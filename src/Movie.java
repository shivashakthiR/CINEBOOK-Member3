
public class Movie {

    // Movie details
    private String name;
    private String genre;
    private int duration;
    private double ticketPrice;

    // Constructor
    public Movie(String name, String genre, int duration, double ticketPrice) {
        this.name = name;
        this.genre = genre;
        this.duration = duration;
        this.ticketPrice = ticketPrice;
    }

}
